const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const Roll = vm.runInNewContext(fs.readFileSync('design/midi-roll.js', 'utf8') + '\nMidiRoll');
const roll = Object.create(Roll.prototype);
const durations = [.37,.24,.57,.94,.33,.95];
let time = .366;
const notes = ['分','开','的','<SP>','时','候'].map((text,i) => {
  const start = time;
  time += durations[i];
  return {text, start, end:time, type:i===3 ? 1 : 2, pitch:[60,62,63,0,65,62][i]};
});
const line = {original:'分开的时候', start:.366, end:time};
const words = ['rest','的','时','候'], mapping = [0,0,1,2,3];
roll.host = {};
roll.draw = () => {};
roll.load(notes,line,null);
roll.update(words,mapping,[]);
assert.deepEqual([...roll.layout()], [0,0,0,1,2,3]);
roll.update(words,mapping,[{index:0,word:'rest',gap_policy:'keep',slots:[]}]);
assert.deepEqual([...roll.layout()], [0,0,1,null,2,3]);
roll.assignment = [0,0,0,1,2,3];
roll.pitches[3] = 64;
roll.setEdge(2,1.56);
roll.edited = true;
assert.equal(roll.start(3),1.56);
assert.equal(roll.pitch(3),64);
assert.equal(roll.error(),'');
const saved = roll.value('a'.repeat(32)+'.wav','rest的时候');
roll.load(notes,line,saved);
roll.update(words,mapping,[]);
assert.equal(roll.start(3),1.56);
assert.equal(roll.pitches[3],64);
assert.deepEqual([...roll.layout()], [0,0,0,1,2,3]);
roll.setEdge(2,10);
assert.ok(roll.ends[3]-roll.ends[2] >= .02-1e-7);
roll.assignment[1] = null;
assert.match(roll.error(), /连续/);
roll.restore(null);
assert.equal(roll.value('unused','rest的时候'),null);
assert.deepEqual(roll.ends,notes.map((n,i) => i===notes.length-1 ? time : Math.round(n.end*1e6)/1e6));
roll.low = 55;
roll.high = 70;
roll.plane = {clientWidth:340, children:notes.map(() => ({style:{}}))};
roll.field = () => ({});
const before = roll.ends.slice();
roll.drag = {i:2, x:0, y:0, pitch:63, override:null, start:before[1], end:before[2],
  prev:before[0], next:before[3]};
roll.moveDrag({clientX:10,clientY:-22});
assert.equal(roll.pitches[2],64);
assert.ok(Math.abs(roll.start(2)-before[1]-.1)<1e-7);
assert.ok(Math.abs(roll.ends[2]-before[2]-.1)<1e-7);
assert.equal(roll.start(4),before[3]);
roll.moveDrag({clientX:0,clientY:0});
assert.equal(roll.pitches[2],null);
assert.equal(roll.ends[2],before[2]);
console.log('MIDI roll mapping, limits and saved draft passed');
